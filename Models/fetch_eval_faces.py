#!/usr/bin/env python
"""Build the M1-T05 face evaluation set from Wikimedia Commons, without hand labeling.

Labels come from the category name (women / men / girls / boys; hijab and profile categories carry the tag).
Only CC0 / CC BY / CC BY-SA files are kept (extmetadata.LicenseShortName); files categorised as nude are
skipped. 800 px thumbnails go to Models/work/faces/ (gitignored, never committed). Committed output is
metadata only: Models/eval/manifest.json and Models/eval/ATTRIBUTIONS.md.
`low-light` entries are synthetic: darkened copies (gamma 2.2, then x0.35) of untagged faces.

usage: Models/venv/bin/python Models/fetch_eval_faces.py [--refresh]
FairFace child faces are added by `Models/fairface.py children` (imports the manifest helpers below).
"""
import html
import json
import os
import re
import sys
import time
import urllib.parse
import urllib.request
from io import BytesIO

import numpy as np
from PIL import Image, ImageOps

HERE = os.path.dirname(os.path.abspath(__file__))
MANIFEST = os.path.join(HERE, "eval", "manifest.json")
ATTRIB = os.path.join(HERE, "eval", "ATTRIBUTIONS.md")
FACES = os.path.join(HERE, "work", "faces")
API = "https://commons.wikimedia.org/w/api.php"
UA = {"User-Agent": "sitr-spike/0.1 (https://github.com/goldentik/sitr; M1-T05 classifier eval set) python-urllib"}
LICENSE_OK = re.compile(r"^(CC0(?: 1\.0)?|CC BY(?:-SA)?(?: \d\.\d)?(?: [a-z]{2}(?:-[a-z]{2})?)?)$", re.I)
NOPE = re.compile(r"nude|naked|topless|erotic", re.I)

# (category, label, tags, wanted). Category names double as labels; parents only, so nude sub-categories stay out.
# Hijab images are mostly group/event shots and the rig keeps only single-face images, so many small categories
# are pooled and near-duplicate upload bursts are capped by title prefix (MAX_PER_PREFIX).
HIJAB = [("Women wearing hijabs", 30), ("Smiling women wearing hijabs", 14), ("Actresses wearing hijabs", 16),
         ("Old women wearing hijabs", 11), ("Surgical technologists in hijabs", 12), ("Women wearing hijabs in Iran", 30),
         ("Women wearing hijabs in Indonesia", 25), ("Women wearing hijabs in Turkey", 20), ("Women wearing hijabs in Malaysia", 15),
         ("Women wearing hijabs in the United States", 30), ("Women wearing hijabs in Egypt", 13), ("Women wearing hijabs in Canada", 20),
         ("Women wearing hijabs in Brazil", 20), ("Women wearing hijabs in the United Kingdom", 15),
         ("Women wearing hijabs in Bangladesh", 15), ("Women wearing hijabs in the Maldives", 15)]
CATEGORIES = [(c, "woman", ["hijab"], n) for c, n in HIJAB] + [
    ("Profile portrait photographs of women", "woman", ["profile"], 25),
    ("Profile portrait photographs of men", "man", ["profile"], 25),
    ("Portrait photographs of girls", "woman", ["child"], 25),
    ("Portrait photographs of boys", "man", ["child"], 25),
    ("Portrait photographs of women", "woman", [], 40),
    ("Portrait photographs of men", "man", [], 40),
]
LOW_LIGHT_PER_LABEL = 15
MAX_PER_PREFIX = 3
seen_ids, prefix_count = set(), {}


def load_manifest():
    if os.path.exists(MANIFEST):
        return json.load(open(MANIFEST))["entries"]
    return []


def save_manifest(entries):
    os.makedirs(os.path.dirname(MANIFEST), exist_ok=True)
    entries = sorted(entries, key=lambda e: e["id"])
    json.dump({"version": 1, "images_dir": "../work/faces", "entries": entries}, open(MANIFEST, "w"), indent=1, ensure_ascii=False)
    write_attributions(entries)
    tags = {}
    for e in entries:
        for t in e["tags"] or ["general"]:
            tags[t] = tags.get(t, 0) + 1
    print(f"manifest: {len(entries)} entries, per tag {tags}")


def write_attributions(entries):
    commons = [e for e in entries if e["source"] == "wikimedia-commons" and not e.get("derived_from")]
    derived = [e for e in entries if e.get("derived_from")]
    fair = [e for e in entries if e["source"].startswith("fairface")]
    out = ["# Evaluation set attributions", "",
           "Generated by `Models/fetch_eval_faces.py` and `Models/fairface.py`. Images are downloaded into",
           "`Models/work/faces/` and never committed; this file and `manifest.json` are the only artefacts.", ""]
    if commons:
        out += [f"## Wikimedia Commons ({len(commons)} files)", "",
                "| File | Author | License | Label | Tags |", "|---|---|---|---|---|"]
        for e in commons:
            out.append(f"| [{e['title']}]({e['page']}) | {e['author']} | [{e['license']}]({e['license_url']}) | {e['label']} | {', '.join(e['tags'])} |")
        out.append("")
    if derived:
        out += [f"{len(derived)} `low-light` entries are darkened copies (gamma 2.2, then x0.35) of files listed above; "
                "see `derived_from` in the manifest.", ""]
    if fair:
        out += [f"## FairFace ({len(fair)} faces)", "",
                "Kärkkäinen, K. & Joo, J. (2021). FairFace: Face Attribute Dataset for Balanced Race, Gender, and Age. WACV.",
                "Mirror: https://huggingface.co/datasets/HuggingFaceM4/FairFace — License: CC BY 4.0 (https://github.com/joojs/fairface).",
                "Entries carry the split and row index in `source`.", ""]
    open(ATTRIB, "w").write("\n".join(out))


def api(params):
    url = API + "?" + urllib.parse.urlencode(dict(params, format="json"))
    with urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=60) as r:
        return json.loads(r.read())


def strip_html(s):
    return html.unescape(re.sub(r"<[^>]+>", "", s or "")).strip() or "unknown"


def fetch_category(cat, label, tags, wanted, refresh):
    entries, cont = [], {}
    while len(entries) < wanted:
        d = api({"action": "query", "generator": "categorymembers", "gcmtitle": "Category:" + cat, "gcmtype": "file",
                 "gcmlimit": 50, "prop": "imageinfo", "iiprop": "url|extmetadata|mime", "iiurlwidth": 800,
                 "iiextmetadatafilter": "LicenseShortName|LicenseUrl|Artist|Categories", **cont})
        for p in sorted(d.get("query", {}).get("pages", {}).values(), key=lambda p: p["pageid"]):
            ii = p["imageinfo"][0]
            meta = {k: v.get("value", "") for k, v in ii.get("extmetadata", {}).items()}
            lic = meta.get("LicenseShortName", "")
            if ii.get("mime") not in ("image/jpeg", "image/png") or not LICENSE_OK.match(lic):
                continue
            if NOPE.search(p["title"] + " " + meta.get("Categories", "")):
                continue
            eid = f"commons_{p['pageid']}"
            prefix = re.sub(r"[\d_\-\s()]+", "", p["title"])[:24].lower()
            if eid in seen_ids or prefix_count.get(prefix, 0) >= MAX_PER_PREFIX:
                continue
            seen_ids.add(eid)
            prefix_count[prefix] = prefix_count.get(prefix, 0) + 1
            path = os.path.join(FACES, eid + ".jpg")
            if refresh or not os.path.exists(path):
                try:
                    with urllib.request.urlopen(urllib.request.Request(ii["thumburl"], headers=UA), timeout=60) as r:
                        img = ImageOps.exif_transpose(Image.open(BytesIO(r.read()))).convert("RGB")
                except Exception as ex:  # ponytail: skip broken files, the category has plenty more
                    print("  skip", p["title"], ex)
                    continue
                img.save(path, quality=92)
                time.sleep(0.2)
            entries.append({"id": eid, "file": eid + ".jpg", "label": label, "tags": tags, "source": "wikimedia-commons",
                            "title": p["title"], "page": ii["descriptionurl"], "url": ii["url"], "thumb": ii["thumburl"],
                            "author": strip_html(meta.get("Artist"))[:120], "license": lic, "license_url": meta.get("LicenseUrl", ""),
                            "derived_from": None, "transform": None})
            if len(entries) >= wanted:
                break
        cont = d.get("continue")
        if not cont:
            break
    print(f"{cat}: {len(entries)}/{wanted} ({label}, {tags})")
    return entries


def darken(entries, refresh):
    out = []
    for label in ("woman", "man"):
        pool = sorted((e for e in entries if e["label"] == label and not e["tags"]), key=lambda e: e["id"])
        for e in pool[:LOW_LIGHT_PER_LABEL]:
            eid = e["id"] + "_dark"
            path = os.path.join(FACES, eid + ".jpg")
            if refresh or not os.path.exists(path):
                a = np.asarray(Image.open(os.path.join(FACES, e["file"])).convert("RGB")).astype("float32") / 255
                Image.fromarray((np.power(a, 2.2) * 0.35 * 255).round().astype("uint8")).save(path, quality=92)
            out.append({**e, "id": eid, "file": eid + ".jpg", "tags": ["low-light"], "derived_from": e["id"],
                        "transform": "gamma 2.2, then brightness x0.35"})
    print(f"low-light: {len(out)} derived copies")
    return out


if __name__ == "__main__":
    refresh = "--refresh" in sys.argv
    os.makedirs(FACES, exist_ok=True)
    keep = [e for e in load_manifest() if e["source"] != "wikimedia-commons"]  # FairFace entries survive a re-run
    commons = []
    for cat, label, tags, wanted in CATEGORIES:
        commons += fetch_category(cat, label, tags, wanted, refresh)
    commons += darken(commons, refresh)
    save_manifest(keep + commons)
